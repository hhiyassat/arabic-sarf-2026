def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('outdir')
    ap.add_argument('--out', required=True)
    args = ap.parse_args()
    lines = []
    for f in sorted(glob.glob(os.path.join(args.outdir, 'test_*.txt'))):
        for l in open(f, encoding='utf-8', errors='ignore'):
            if l.startswith('PASS '):
                lines.append((os.path.basename(f)[:-4], l[5:].strip()))
    reg = []
    for iid, desc, kws in ITEMS:
        hits = [dict(test=t, check=c[:160]) for t, c in lines if any(k in c for k in kws)]
        # المعرّف المختصر للفحص (أول كلمة) يُحفظ ليُتحقَّق من بقائه في ملف الاختبار
        for h in hits:
            h['check_id'] = h['check'].split(' ')[0]
        reg.append(dict(id=iid, description=desc, keywords=kws, tests=hits[:40], n_tests=len(hits),
                        status='PROTECTED' if hits else 'GAP: لا اختبار مرتبط'))
    json.dump(dict(source=os.path.abspath(args.outdir), items=reg), open(args.out, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    for r in reg:
        print(r['id'], r['status'], r['n_tests'])


if __name__ == '__main__':
    main()
