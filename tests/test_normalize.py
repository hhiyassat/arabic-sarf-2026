#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
اختبارات التطبيع العثماني بترميزي تنزيل ومصحف المجمّع (KFGQPC).

    python3 tests/test_normalize.py
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from sarf.normalize import uthmani_normalize

CASES = [
    # التنوين «المفتوح» (ࣰ ࣱ ࣲ) صورةٌ للتنوين
    ('مِهَٰدࣰا', 'مِهَٰدًا'),
    ('أَجَلࣲ', 'أَجَلٍ'),
    # الهمزة المنفصلة عن كرسيّها بحركة
    ('مَـَٔابࣰا', 'مَءَابًا'),
    ('لِقَاۤىِٕ', 'لِقَائِ'),
    ('ٱللُّؤۡلُوِٕ', 'اللُّؤْلُؤِ'),
    ('فَٱدَّٰرَٰٔتُمۡ', 'فَادَّٰرَأْتُمْ'),
    ('ٱلۡأٓخِرَةِ', 'الْآخِرَةِ'),
    # ْ في مصحف المجمّع صفرٌ على الحرف الزائد، وسكونه ۡ
    ('كَفَرُواْ يُكَذِّبُونَ', 'كَفَرُوا يُكَذِّبُونَ'),
    ('أُوْلَٰٓئِكَ هُمُ ٱلۡمُفۡلِحُونَ', 'أُلَٰئِكَ هُمُ الْمُفْلِحُونَ'),
    ('وَجِاْيٓءَ يَوۡمَئِذِۭ', 'وَجِيءَ يَوْمَئِذِ'),
    # الصفر المستدير (۟) في تنزيل: الحرف الزائد يُحذف، إلا الألف الفارقة بعد الواو
    ('ءَامَنُوٓا۟', 'ءَامَنُوا'),
    ('وَجِا۟ىٓءَ', 'وَجِىءَ'),
    ('ٱلْعُلَمَٰٓؤُا۟', 'الْعُلَمَٰؤُ'),
    # الكشف عن الرسم العثماني قبل حذف الخنجرية: السكون المضمر على النون
    ('إِلَىٰ رَبِّكَ مُنتَهَىٰهَآ', 'إِلَى رَبِّكَ مُنْتَهَىهَا'),
    # ترميز تنزيل: ْ سكون
    ('فَٱكْتُبُوهُ', 'فَاكْتُبُوهُ'),
    # الكشف قبل NFC (ٓ تُدمج في آ)، وبالتنوين المفتوح والهمزة المنفصلة
    ('ثُمَّ جَا\u0653ءَهُم مَّا', 'ثُمَّ جَاءَهُمْ مَّا'),
    ('إِنَّكَ كُنتَ بِنَا بَصِيرࣰا', 'إِنَّكَ كُنْتَ بِنَا بَصِيرًا'),
    # الصفر على الألف بعد واو مفتوحة: الألف زائدة تُحذف (ٱلرِّبَوٰاْ)
    ('ٱلرِّبَوٰاْ', 'الرِّبَوٰ'),
    # الإدغام الكامل: الحرف العاري قبل المشدَّد لا يُسكَّن
    ('لِّلنَّاسِ وَٱلۡأَرۡضِ', 'لِّلنَّاسِ وَالْأَرْضِ'),
    ('عَٰهَدتَّ وَٱلۡأَرۡضِ', 'عَٰهَدتَّ وَالْأَرْضِ'),
]

bad = 0
for src, want in CASES:
    got = uthmani_normalize(src)
    ok = got == want
    bad += not ok
    print('OK ' if ok else 'BAD', src, '' if ok else f'→ {got} (المتوقَّع {want})')
print('ALL OK' if not bad else f'FAILED {bad}')
sys.exit(1 if bad else 0)
