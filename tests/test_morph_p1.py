for t, exp, why, *wi in POS + NEG:
    got = slots(t, wi[0] if wi else 0)
    if exp is None:   # شرطٌ لا صورة: لا «أَ» مفصولة
        ok = not any(x == (M, 'أَ') for x in got)
        check(f'{why}: {t}', ok, got)
    else:
        check(f'{why}: {t}', got == exp, got)
print(f'CHECKS pass={N[0] - len(FAIL)} fail={len(FAIL)} total={N[0]}')
print('ALL OK' if not FAIL else f'FAILED {len(FAIL)}: {FAIL}')
sys.exit(1 if FAIL else 0)
