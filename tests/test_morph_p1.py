import os, sys
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, H)
from sarf.analyze import analyze
from sarf.catalog import Catalog
cat = Catalog([os.path.join(H, 'operators_catalog.jsonl'), os.path.join(H, 'operators_catalog_split_vocalized.csv')])
FAIL, N = [], [0]


def slots(text, wi=0):
    return [(s['type'], s['text']) for s in analyze(cat, text)['segments'][wi]['slots']]


def check(name, ok, got=''):
    N[0] += 1
    print(('PASS ' if ok else 'FAIL ') + name + ('' if ok else f' — {got}'))
    if not ok:
        FAIL.append(name)


