    ('قَدْ بَيَّنَّا الْءَايَٰتِ', [(S, 'بَيَّنَّا')], '«نَّا» بعد نونٍ مشدَّدة من الفعل', 1),
    ('الْتَقَى الْجَمْعَانِ', [(S, 'الْتَقَى')], 'لامٌ ساكنة قبل التاء غير المشدَّدة: ليست «أل»'),
