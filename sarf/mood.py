"""
sarf.mood — خبري/إنشائي بالعامل في بابه، كما في سجل T14.
"""
import unicodedata

from .status import BLOCKED

# ── تصنيف خبري/إنشائي (معيار القسمة المعتمد، Q01؛ وT12 وT14a) ──
# إنشائي: مساهمة العامل فعلٌ يقع بالتلفّظ ولا يُردّ إلى تقييد مضمون آخر:
#         الطلب (النداء، والأمر، والنهي، والتمني) والإيقاع (المدح والذم).
# خبري:   مساهمته بناء مضمون أو تعيين علاقة أو تقييدها، ومنه التوكيد والتوقّع والمبالغة:
#         فالقسم (وَ، تَ، ومعنى القسم في بِ) والرجاء (لَعَلَّ، عَسَى) ورُبَّ
#         وأسماء أفعال الماضي (هَيْهَاتَ، شَتَّانَ، سُرْعَانَ) خبرية.
# مؤجَّل: وحدةٌ اختلفت استعمالاتها في الفهرس (T14a): لَوْ (الشرط خبري، والتمني طلب)،
#         وكَمْ (الخبرية خبر، والاستفهامية طلب). يُحكم للاستعمال حين يُعيَّن، لا للوحدة.
def _nfc(s):
    return unicodedata.normalize('NFC', s or '')

# ── تصنيف خبري/إنشائي بالعامل في بابه (المفتاح: الصيغة بعد NFC، والمجموعة) كما في سجل T14 ──
# الإنشائي 18 وحدةً فقط، وكل ما عداها خبري. المقارنة بعد NFC لاختلاف ترتيب العلامات بين الفهرس والكود.
MOOD = {(_nfc(form), group): 'in' for form, group in (
    # المجموعة 4 — النداء الخمسة
    ('يَا', '4'), ('أَيَا', '4'), ('هَيَا', '4'), ('أَيْ', '4'), ('أَ', '4'),
    # المجموعة 6 — لام الأمر ولا الناهية
    ('لِ', '6'), ('لَا', '6'),
    # المجموعة 2 — التمني
    ('لَيْتَ', '2'),
    # المجموعة 9 — أسماء أفعال الأمر الستة (دون أسماء أفعال التعجب)
    ('رُوَيْدَ', '9'), ('بَلْهَ', '9'), ('دُونَكَ', '9'), ('عَلَيْكَ', '9'), ('هَاءَ', '9'), ('حَيَّهَلَ', '9'),
    # المجموعة 12 — المدح والذم (إنشائي غير طلبي)
    ('نِعْمَ', '12'), ('بِئْسَ', '12'), ('سَاءَ', '12'), ('حَبَّذَا', '12'),
)}


MOOD_DEFERRED = {(_nfc(form), group): reason for form, group, reason in (
    ('لَوْ', '7', 'الشرط الامتناعي خبري، والتمني طلب'),
    ('كَمْ', '8', 'الخبرية للكثرة خبر، والاستفهامية طلب'),
)}


def op_mood(f):
    """خبري/إنشائي/مؤجَّل لعاملٍ واحد بمفتاحه (الصيغة، المجموعة)."""
    key = (_nfc(f.get('operator')), f.get('group'))
    if key in MOOD_DEFERRED:
        return 'مؤجَّل'
    return 'إنشائي' if MOOD.get(key) == 'in' else 'خبري'


def has_inshai_operator(ops):
    """هل في الآية عاملٌ إنشائيٌّ غير مرفوض؟ (لا يشمل الإنشاء بالصيغ — T13)"""
    return any(op_mood(f) == 'إنشائي' and f.get('status') != BLOCKED for f in ops)
